# frozen_string_literal: true

Given('log archival is configured for a disposable object store') do
  prepare_archive_publication
end

Given('a log batch staged on the previous database schema') do
  stage_before_publication
end

Given('an acknowledged log batch staged with a different Parquet encoding') do
  stage_with_different_parquet_encoding
end

Given('an acknowledged log batch staged for multipart upload') do
  stage_with_different_parquet_encoding(multipart: true)
end

Given('acknowledged log batches are staged for two archive days') do
  stage_two_archive_batches
end

When('the service accepts and publishes a log export') do
  publish_log_archive
end

When('the service restarts after the object store commits an unacknowledged upload and staging is lost') do
  recover_ambiguous_publication
end

When('the upgraded service publishes the staged batch') do
  publish_staged_log_archive
end

When('the service stops during a multipart upload and restarts') do
  recover_interrupted_multipart_publication
end

When('the store serves different bytes during verification and then serves the correct object') do
  recover_from_checksum_mismatch
end

When('another writer creates the same key with different bytes and the {string} checksum before completion') do |metadata|
  publish_against_competing_object(metadata)
end

When('the original upload commits as the restarted service tries to upload regenerated bytes') do
  recover_late_original_upload
end

When('staging cleanup fails and the service restarts after write access returns') do
  recover_failed_archive_cleanup
end

When('the service restarts after an unacknowledged commit and cannot recreate the lost staged file') do
  reconcile_without_restaging
end

When('startup reconciles an unacknowledged upload while removal of its corrupt staged file is blocked') do
  recover_corrupt_staging_cleanup
end

When('the service restarts after an unacknowledged commit with the staged file still unreadable') do
  reconcile_unreadable_staging
end

When('the staged file is corrupted during a store outage and access returns') do
  recover_live_corrupt_staging
end

When('the service starts with an unreadable staged batch and only the later upload committed') do
  reconcile_past_missing_object
end

When('the service publishes while the earlier staging directory is unwritable') do
  publish_past_blocked_cleanup
end

When('a staged file is corrupted and its directory is unwritable as logs arrive for another day') do
  publish_past_blocked_repair
end

Then('only the newly accepted logs should be published and the blocked staging file should remain') do
  expect(@published_keys.size).to eq(1)
  expect(@published_rows).to have_stored_log_export(@later_archive_request)
  expect(@retained_staging_files).to eq([@first_archive_path])
end

Then('the batch should be published under its original archive key') do
  expect(@published_keys).to eq([@original_publication_key])
end

Then('the earlier batch should remain unconfirmed and the later batch should be reclaimed') do
  expect(@interrupted_publication).to retain_only_earlier_staging(@earlier_key, @later_key, @staged_checksums, false)
  expect(@visible_objects).to match_archive_key_checksums(@staged_checksums, @later_key)
end

Then('both batches should be confirmed and only the later batch should be reclaimed') do
  expect(@interrupted_publication).to retain_only_earlier_staging(@earlier_key, @later_key, @staged_checksums, true)
  expect(@visible_objects).to match_archive_key_checksums(@staged_checksums, @earlier_key, @later_key)
end

Then('the corrupt staged file should have remained pending for cleanup after confirmation') do
  expect(@interrupted_publication).to retain_pending_corrupt_staging(@ambiguous_objects.values.fetch(0))
end

Then('the existing archive should be confirmed despite the failed restaging') do
  expect(@restaging_failed).to be(true)
end

Then('the batch should have stayed unconfirmed with its staged file intact') do
  expect(@interrupted_publication).to retain_staging_with_publication_status(false)
end

Then('the batch should have stayed confirmed with its staged file intact') do
  expect(@interrupted_publication).to retain_staging_with_publication_status(true)
end

Then('the competing object should still have its original bytes') do
  expect(@visible_objects.values).to eq([@competing_checksum])
end

Then('the confirmed checksum should be the earlier of the two attempted checksums') do
  expect(@attempted_checksums.uniq.size).to eq(2)
  expect(@published_objects.values).to eq([@attempted_checksums.first])
end

Then('the unfinished upload should be aborted while the staged batch remains available') do
  expect(@uploads_before_stop.size).to eq(1)
  expect(@uploads_after_stop).to be_empty
  expect(@objects_after_stop).to be_empty
  expect(@staging_after_stop.size).to eq(1)
end

Then('the object store should contain one Parquet batch with the accepted logs') do
  expect(@published_keys.size).to eq(1)
  expect(@published_rows).to have_stored_log_export(@archive_request)
end

Then('the published batch should be recorded and its staging file reclaimed') do
  expect(@published_state.size).to eq(1)
  id, day, _, staged, checksum, published, cleaned = @published_state.fetch(0)
  expect(@published_objects).to eq("v1/signal=logs/day=#{day}/#{id}.parquet" => checksum)
  expect([published, cleaned, staged, @retained_staging_files]).to eq([true, true, nil, []])
end

Then('the acknowledged logs should still be queryable locally') do
  expect(@archive_query_response.code).to eq(200)
  page = Einblick::V1::ListLogsResponse.decode_json(@archive_query_response.body)
  expect(page.logs.map(&:record)).to match_array(log_query_records(@archive_request))
end

Then('the original archive object should remain unchanged') do
  expect(@published_objects).to eq(@ambiguous_objects)
end

Then('the original batch identity and membership should be preserved') do
  expect(@published_state.map { |batch| batch.take(3) }).to eq(@original_archive_batches.map { |batch| batch.take(3) })
  expect(@archive_members).to eq(@original_archive_members)
end
