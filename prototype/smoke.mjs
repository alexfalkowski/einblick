import {spawn} from 'node:child_process';
import {readFile,writeFile,mkdir,mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {setTimeout as delay} from 'node:timers/promises';
const dir=fileURLToPath(new URL('.',import.meta.url));
const profile=await mkdtemp(join(tmpdir(),'einblick-chrome-'));
await mkdir(join(dir,'screenshots'),{recursive:true});
await mkdir(join(dir,'validation'),{recursive:true});
const chromeArgs=['--headless=new','--disable-gpu','--disable-dev-shm-usage','--remote-debugging-port=0','--user-data-dir='+profile,'about:blank'];
if(process.env.CHROME_NO_SANDBOX==='1')chromeArgs.unshift('--no-sandbox');
const chrome=spawn(process.env.CHROME_BIN||'google-chrome',chromeArgs,{stdio:['ignore','ignore','ignore']});
let launchError;chrome.on('error',error=>{launchError=error});
let ws;
const checks=[];
try {
 let port;
 for(let i=0;i<60;i++){try{if(launchError)throw launchError;port=(await readFile(join(profile,'DevToolsActivePort'),'utf8')).split('\n')[0];break}catch(error){if(launchError)throw launchError;await delay(100)}}
 if(!port)throw new Error('Chrome did not expose CDP');
 const tab=await(await fetch('http://127.0.0.1:'+port+'/json/new?about:blank',{method:'PUT'})).json();
 ws=new WebSocket(tab.webSocketDebuggerUrl);
 await new Promise((resolve,reject)=>{ws.addEventListener('open',resolve,{once:true});ws.addEventListener('error',reject,{once:true})});
 const pending=new Map();let seq=0;
 ws.addEventListener('message',event=>{const m=JSON.parse(event.data);if(m.id&&pending.has(m.id)){const p=pending.get(m.id);pending.delete(m.id);m.error?p.reject(new Error(JSON.stringify(m.error))):p.resolve(m.result)}});
 const call=(method,params={})=>new Promise((resolve,reject)=>{const id=++seq;pending.set(id,{resolve,reject});ws.send(JSON.stringify({id,method,params}))});
 const ev=async expression=>{const r=await call('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw new Error(JSON.stringify(r.exceptionDetails));return r.result.value};
 const check=async(name,expression)=>{if(!await ev(expression))throw new Error('Failed: '+name);checks.push(name)};
 const click=async selector=>{await ev('document.querySelector('+JSON.stringify(selector)+').click()')};
 const shot=async name=>{await delay(100);const r=await call('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});await writeFile(join(dir,'screenshots',name+'.png'),Buffer.from(r.data,'base64'))};
 await call('Page.enable');
 await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1180,deviceScaleFactor:1,mobile:false});
 await call('Page.navigate',{url:new URL('index.html',import.meta.url).href});
 for(let i=0;i<50;i++){if(await ev('document.body?.dataset.ready === "true"'))break;await delay(50)}
 await check('Overview renders eight built-in charts','plots.length===8 && !document.body.dataset.error');
 await check('Synthetic trace IDs are distinct','new Set(dataset().traces.map(t=>t.id)).size===12');
 await shot('overview');
 await click('[data-tab="logs"]');
 await check('Logs show bounded page','document.querySelectorAll("[data-log]").length===12');
 await click('[data-action="next"]');
 await check('Logs advance to the second page','document.querySelectorAll("[data-log]").length===12 && document.querySelector(".result-footer").textContent.includes("Showing 13–24 of 24 records")');
 await ev('document.getElementById("instance").value="0";document.getElementById("instance").dispatchEvent(new Event("change",{bubbles:true}))');
 await check('Instance changes reset log pagination','document.querySelectorAll("[data-log]").length===12 && document.querySelector(".result-footer").textContent.includes("Showing 1–12 of 12 records")');
 await ev('document.getElementById("instance").value="all";document.getElementById("instance").dispatchEvent(new Event("change",{bubbles:true}))');
 await click('[data-action="next"]');
 await ev('document.getElementById("time-range").value="300";document.getElementById("time-range").dispatchEvent(new Event("change",{bubbles:true}))');
 await check('Time range changes reset log pagination','document.querySelectorAll("[data-log]").length===12 && document.querySelector(".result-footer").textContent.includes("Showing 1–12 of 19 records")');
 await ev('document.getElementById("time-range").value="900";document.getElementById("time-range").dispatchEvent(new Event("change",{bubbles:true}))');
 await click('[data-action="next"]');
 await click('[data-log="12"]');
 await click('[data-action="context-logs"]');
 await check('Surrounding logs reset log pagination','document.querySelectorAll("[data-log]").length===7 && document.querySelector(".result-footer").textContent.includes("Showing 1–7 of 7 records")');
 await click('[data-action="clear-selection"]');
 await shot('logs');
 await click('[data-log="0"]');
 await check('Log drawer opens','document.querySelector(".inspector").textContent.includes("Record attributes")');
 await shot('log-detail');
 await click('.inspector [data-trace]');
 await check('Log links to trace waterfall','document.querySelectorAll(".span-row").length===8');
 await click('[data-span="5"]');
 await check('Span inspection changes selection','state.span===5 && document.querySelectorAll(".span-row.selected").length===1');
 await shot('trace-detail');
 await click('.inspector [data-action="related-logs"]');
 await check('Trace links to filtered related logs','state.tab==="logs" && filteredLogs().length>0 && filteredLogs().every(l=>l.traceId===state.traceFilter)');
 await click('[data-action="reset-filters"]');
 await ev('document.getElementById("search").value="request failed";document.getElementById("search").dispatchEvent(new Event("input",{bubbles:true}))');
 await check('Log search filters rows','filteredLogs().length>0 && filteredLogs().every(l=>l.message.includes("request failed"))');
 await click('[data-tab="traces"]');
 await shot('traces');
 await click('[data-action="errors"]');
 await check('Trace error filter works','filteredTraces().length===2 && filteredTraces().every(t=>t.error)');
 await click('[data-service="web"]');
 await click('[data-tab="overview"]');
 await check('HTTP-only services omit gRPC panels','plots.length===4 && !document.querySelector("section[data-protocol=grpc]")');
 await click('[data-service="bezeichner"]');
 await ev('plots[0].setSelect({left:160,top:0,width:45,height:60})');
 await delay(50);
 await check('Chart range selection appears','selectedWindow!==null && document.querySelector(".selection-notice")!==null');
 await click('[data-action="selected-logs"]');
 await check('Chart selection carries into log filtering','filteredLogs().every(l=>l.time>=selectedWindow[0] && l.time<selectedWindow[1]) && location.hash.includes("from=")');
 await click('[data-action="clear-selection"]');
 await click('[data-action="empty"]');
 await check('Empty state remains distinct from zero','document.getElementById("view").textContent.includes("Waiting for log records")');
 await click('[data-tab="overview"]');
 await check('Empty overview uses dashes','plots.length===0 && [...document.querySelectorAll(".stat-value")].every(e=>e.textContent==="—")');
 await shot('empty-state');
 await click('[data-action="empty"]');
 await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
 await delay(150);
 await shot('mobile');
 await check('Mobile layout fits viewport','document.documentElement.scrollWidth<=innerWidth');
 await check('No browser runtime error','!document.body.dataset.error');
 await writeFile(join(dir,'validation','smoke-results.json'),JSON.stringify({checks,passed:checks.length},null,2));
 process.stdout.write(JSON.stringify({passed:checks.length,checks},null,2)+'\n');
} finally {
 ws?.close();
 if(chrome.exitCode===null&&!launchError){
  await new Promise(resolve=>{const timeout=setTimeout(()=>{chrome.kill('SIGKILL');resolve()},2000);chrome.once('exit',()=>{clearTimeout(timeout);resolve()});chrome.kill('SIGTERM')});
 }
 await rm(profile,{recursive:true,force:true});
}
